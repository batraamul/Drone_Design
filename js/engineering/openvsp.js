/**
 * OpenVSP bridge (Build 6): writes an OpenVSP AngelScript (.vspscript) that rebuilds the
 * conceptual geometry — wing, fuselage pod, tail surfaces, booms, rotor discs — so it can
 * be refined and analysed in OpenVSP (VSPAERO, Parasite Drag, mass properties).
 *
 * Run it in OpenVSP with File → Run Script…, or `vspscript -script <file>`.
 *
 * Frames: AEROLAB X is x forward, z up, metres; OpenVSP is X aft, Z up, model units
 * (set to metres here). Hence X_vsp = −x. Wing parameters per section: Span is one side,
 * Sweep is at the leading edge, angles in degrees.
 */
const DEG = 180 / Math.PI;
const num = (v) => (Number.isFinite(v) ? Number(v.toFixed(6)).toString() : '0');
const safe = (s) => String(s ?? '').replace(/[^\w .()-]/g, '').slice(0, 60) || 'AEROLAB X design';

export function vspScript(geometry, { name = 'AEROLAB X design', appVersion = '' } = {}) {
  if (!geometry) return null;
  const L = [];
  const set = (id, parm, group, value) => L.push(`    SetParmVal( ${id}, "${parm}", "${group}", ${num(value)} );`);
  const place = (id, p, rot = null) => {
    set(id, 'X_Rel_Location', 'XForm', -p.x);
    set(id, 'Y_Rel_Location', 'XForm', p.y);
    set(id, 'Z_Rel_Location', 'XForm', p.z);
    if (rot) {
      if (rot.x !== undefined) set(id, 'X_Rel_Rotation', 'XForm', rot.x);
      if (rot.y !== undefined) set(id, 'Y_Rel_Rotation', 'XForm', rot.y);
      if (rot.z !== undefined) set(id, 'Z_Rel_Rotation', 'XForm', rot.z);
    }
  };
  const surface = (id, label, { span, root, tip, sweepLE = 0, dihedral = 0, symmetric = true, at, rot = null }) => {
    L.push(`    string ${id} = AddGeom( "WING", "" );`);
    L.push(`    SetGeomName( ${id}, "${label}" );`);
    if (!symmetric) set(id, 'Sym_Planar_Flag', 'Sym', 0);
    set(id, 'Span', 'XSec_1', span);
    set(id, 'Root_Chord', 'XSec_1', root);
    set(id, 'Tip_Chord', 'XSec_1', tip);
    set(id, 'Sweep', 'XSec_1', sweepLE * DEG);
    set(id, 'Sweep_Location', 'XSec_1', 0);
    set(id, 'Dihedral', 'XSec_1', dihedral * DEG);
    place(id, at, rot);
    L.push('    Update();');
  };
  L.push(`// OpenVSP script generated by AEROLAB X ${appVersion} — "${safe(name)}"`);
  L.push('// Conceptual geometry only: flat-plate sections. Set aerofoils, thickness and details in OpenVSP.');
  L.push('// Run with File → Run Script… (OpenVSP 3.x). Units: metres. X aft, Z up.');
  L.push('void main()');
  L.push('{');
  L.push('    SetVSP3FileName( "aerolab_x_design.vsp3" );');
  const w = geometry.wing;
  if (w) {
    surface('wing', 'Wing', { span: w.span / 2, root: w.rootChord, tip: w.tipChord, sweepLE: w.sweepLE ?? 0, dihedral: w.dihedral ?? 0, at: { x: w.xRootLE, y: 0, z: 0 } });
  }
  const f = geometry.fuselage;
  if (f?.length > 0 && f.diameter > 0) {
    L.push('    string fuse = AddGeom( "POD", "" );');
    L.push('    SetGeomName( fuse, "Fuselage" );');
    set('fuse', 'Length', 'Design', f.length);
    set('fuse', 'FineRatio', 'Design', f.length / f.diameter);
    place('fuse', { x: 0, y: 0, z: 0 });
    L.push('    Update();');
  } else if (geometry.body) {
    L.push('    string body = AddGeom( "POD", "" );');
    L.push('    SetGeomName( body, "Centre body" );');
    set('body', 'Length', 'Design', geometry.body.diameter);
    set('body', 'FineRatio', 'Design', geometry.body.diameter / Math.max(geometry.body.height, 0.01));
    place('body', { x: geometry.body.diameter / 2, y: 0, z: 0 });
    L.push('    Update();');
  }
  const t = geometry.tail;
  if (t?.type === 'conventional') {
    surface('htail', 'Horizontal tail', { span: t.span / 2, root: t.chord, tip: t.chord, at: { x: t.xLE, y: 0, z: 0 } });
    surface('vtail', 'Vertical tail', { span: t.vHeight, root: t.vChord, tip: t.vChord, symmetric: false, at: { x: t.xLEv ?? t.xLE, y: 0, z: 0 }, rot: { x: 90 } });
  } else if (t?.type === 'v') {
    surface('vtail', 'V-tail', { span: t.span / 2 / Math.cos(t.angle), root: t.chord, tip: t.chord, dihedral: t.angle, at: { x: t.xLE, y: 0, z: 0 } });
  }
  (geometry.booms ?? []).forEach((b, i) => {
    const len = Math.hypot(b.to.x - b.from.x, b.to.y - b.from.y, b.to.z - b.from.z);
    L.push(`    string boom${i} = AddGeom( "POD", "" );`);
    L.push(`    SetGeomName( boom${i}, "Boom ${i + 1}" );`);
    set(`boom${i}`, 'Length', 'Design', len);
    set(`boom${i}`, 'FineRatio', 'Design', len / 0.025);
    place(`boom${i}`, b.from.x >= b.to.x ? b.from : b.to);
    L.push('    Update();');
  });
  (geometry.rotors ?? []).forEach((r, i) => {
    const id = `rotor${i}`;
    L.push(`    string ${id} = AddGeom( "PROP", "" );`);
    L.push(`    SetGeomName( ${id}, "Rotor ${i + 1} (${r.role}, ${r.spin})" );`);
    set(id, 'Diameter', 'Design', r.diameter);
    // PROP geometry spins about its own X axis: lift rotors point up (Y rotation −90°).
    place(id, r, r.axis === 'z' ? { y: -90 } : null);
    L.push('    Update();');
  });
  L.push('    Update();');
  L.push('    WriteVSPFile( GetVSPFileName(), SET_ALL );');
  L.push('    Print( "AEROLAB X geometry created." );');
  L.push('}');
  return `${L.join('\n')}\n`;
}
